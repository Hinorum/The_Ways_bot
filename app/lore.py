def _narrowed_card(
    card: CardDraft,
    tag: str,
    history_tags: list[str],
    day_index: int,
    salt: str,
) -> CardDraft:
    """Эхо-сужение арены: выбор стаи «прорастает», а не генерируется в вакууме.

    Окно 7 дней. Если архетип «горячий» (встречался >=3 раз) — карта получает
    заряженное эхо-окончание, подтянутое под уже выбранную тропу. Если архетип
    «мёрзлый» (0 появлений) и стая при этом принимала решения (история не
    пуста) — в карту Администратор подмешивает чужую подпись-ловушку, и выбор
    оборачивается негативным эхом. Детерминировано по (день, соль, тэг, след).
    """
    window = [t for t in history_tags if t][-7:]
    if not window:
        return card
    count = window.count(tag)
    hot = count >= 3
    frozen = count == 0
    if not hot and not frozen:
        return card
    rng = _rng(day_index, f"echo:{tag}:{'|'.join(window)}:{salt}")
    if hot:
        warm = (
            " Стая уже знает эту тропу: её нос помнит, как пахнет подобный выбор.",
            " След знаком — стая делала это недавно и знает цену заранее.",
        )
        return replace(
            card,
            description=card.description + warm[rng.randrange(len(warm))],
        )
    tail = _TRAP_TAILS[rng.randrange(len(_TRAP_TAILS))]
    return replace(card, consequence=card.consequence + tail)


def _card_variant(description: str, consequence: str, day_index: int, salt: str = "") -> tuple[str, str]:
    """Returns (description, consequence) with minor deterministic variations."""
    rng = random.Random(f"cardvar:{day_index}:{salt}:{hash(description)}")

    variants = [
        # Identity - keep original
        lambda d, c: (d, c),
        # Sensory: add temperature detail
        lambda d, c: (d + " Воздух пахнет озоном и чем-то металлическим.", c),
        # Time pressure: add urgency
        lambda d, c: (d + " Время на исходе.", c),
        # Perspective: shift to second person
        lambda d, c: (d.replace("стая", "ты"), c),
        # Sensory: add visual detail
        lambda d, c: (d + " Свет дрожит на краю зрения.", c),
        # Sensory: add tactile detail
        lambda d, c: (d + " Земля под лапами вибрирует.", c),
        # Emotional: add tension
        lambda d, c: (d + " Что-то в воздухе изменилось.", c),
        # Sensory: add smell
        lambda d, c: (d + " Запах дыма смешался с пылью.", c),
        # Rhythm: break into shorter sentence
        lambda d, c: (d.rstrip(".") + ". Нужно решать.", c),
        # Consequence: add temporal marker
        lambda d, c: (d, c + " Это случится скоро."),
        # Consequence: add uncertainty
        lambda d, c: (d, c + " Или нет."),
        # Sensory: add sound
        lambda d, c: (d + " Где-то щёлкнул счётчик.", c),
        # Emotional: add stakes
        lambda d, c: (d + " Стая чувствует вес выбора.", c),
        # Identity - keep original
        lambda d, c: (d, c),
    ]

    idx = rng.randint(0, len(variants) - 1)
    return variants[idx](description, consequence)


