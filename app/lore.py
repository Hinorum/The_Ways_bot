def _rng(day_index: int, salt: str) -> random.Random:
    seed = int(hashlib.sha256(f"{day_index}:{salt}".encode()).hexdigest()[:16], 16)
    return random.Random(seed)


def _tag_for_beat(beat: str) -> str:
    """Точный тег по названию карты. Названия путей — авторские строки этого
    же модуля, поэтому сверяем по ним, а не по ключевым словам в описании:
    иначе «Красный сигнал», «Тихий лаз» или «Обходной след» без «игл» в
    названии силой помечались «care», и тон главы спорил с показанными картами."""
    title = beat.split(":", 1)[0].strip().strip("«»\"'").lower()
    return _TITLE_TAG.get(title, "")


def tags_from_beats(previous_beats: list[str]) -> list[str]:
    """Тег каждого прожитого дня. Сначала точное совпадение названия карты
    (_tag_for_beat), иначе — ключевой скан описания. Точное совпадение чинит
    системную ошибку, когда рисковые/хитрые пути без «игл» в названии
    силой попадали в «care»."""
    tags: list[str] = []
    mapping = {
        "лай": "risk",
        "искр": "risk",
        "зуб": "risk",
        "глаз": "risk",
        "голод": "risk",
        "портал": "cunning",
        "архив": "cunning",
        "мутант": "cunning",
        "глюк": "cunning",
        "имя": "cunning",
        "кост": "care",
        "стая": "care",
        "дом": "care",
        "тепл": "care",
        "лун": "care",
        "сон": "care",
    }
    for beat in previous_beats:
        exact = _tag_for_beat(beat)
        if exact:
            tags.append(exact)
            continue
        low = beat.lower()
        for needle, tag in mapping.items():
            if needle in low:
                tags.append(tag)
                break
        else:
            tags.append("care")
    return tags


def chapter_tone(tags: list[str]) -> str:
    """Единый тон главы для эха и мотива.

    Раньше эхо при равенстве счётов брало «care» (==«тише»), а мотив — «risk»
    (==«громче»), и одна глава выходила и тише, и громче сразу. Теперь тон
    считается один раз; при равенстве приоритет у более «активного» тона:
    риск → хитрость → забота."""
    if not tags:
        return "care"
    counts = {t: tags.count(t) for t in ("risk", "care", "cunning")}
    priority = ["risk", "cunning", "care"]
    return max(priority, key=lambda t: (counts[t], -priority.index(t)))


