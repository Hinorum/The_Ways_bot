# День забега, когда вечерний привал заменяется находкой страницы.
# Каждые 4 дня — так все 6 страниц успевают попасться даже в короткий
# месячный забег (28 дней в феврале): последняя, манифест Еретика,
# приходится на день 24.
COUNCIL_DAY_MODULO = 4


def page_for_run_day(run_day: int) -> str | None:
    """Текст страницы для дня забега или None (день обычного привала).

    Ротация без состояния: слот = номер четырёхдневки; внутри слота страница
    стабильна, между слотами — следующая по кругу.
    """
    if run_day <= 0 or run_day % COUNCIL_DAY_MODULO != 0:
        return None
    slot = run_day // COUNCIL_DAY_MODULO
    return _COUNCIL_PAGES[(slot - 1) % len(_COUNCIL_PAGES)]
